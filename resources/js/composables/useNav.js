export function useNav() {
    const page = usePage();

    const items = computed(() => {
        const can = page.props.can ?? {};
        return [
            { label: 'Início', route: 'dashboard', match: 'dashboard', icon: icons.home },
            { label: 'Escalas', route: 'schedules.index', match: ['schedules.*', 'services.*'], icon: icons.calendar },
            { label: 'Músicas', route: 'songs.index', match: 'songs.*', icon: icons.music },
            can.admin && { label: 'Equipe', route: 'members.index', match: 'members.*', icon: icons.users },
            can.admin && { label: 'Ajustes', route: 'settings.index', match: 'settings.*', icon: icons.settings },
        ].filter(Boolean);
    });

    const isActive = (item) => [].concat(item.match).some((pattern) => route().current(pattern));

    return { items, isActive };
}
